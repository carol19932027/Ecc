async function runRecommendation(query) {
  try {
    let data = null;
    try {
      const res = await fetch('/api/recommend', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ query }),
      });
      if (res.ok) data = await res.json();
    } catch {
      // Static preview fallback below
    }
    if (!data?.ok) {
      if (!state.catalog.length) await fetchCatalog();
      data = { ok: true, ...recommendLocally(query, state.catalog) };
    }
    if (!data || !data.ok) throw new Error('Recommendation failed');

    state.lastAiCommand = data.command;
    $('#ai-cmd-text').textContent = data.command;
    $('#ai-command-box').hidden = false;

    $('#ai-results-grid').innerHTML = (data.matches || []).map(item => `
      <button type="button" class="comp-card interactive-glass" data-open-kind="${escapeHtml(item.kind)}" data-open-id="${escapeHtml(item.id)}">
        <div class="comp-top">
          <span class="kind-badge glass-pill">${escapeHtml(item.kind)}</span>
          <span class="kpi-badge">score ${item.score ?? 10}</span>
        </div>
        <h3 class="comp-title">${escapeHtml(item.id)}</h3>
        <p class="comp-desc">${escapeHtml(item.description)}</p>
      </button>
    `).join('');

    logActivity(`Command AI matched ${data.matches.length} components for "${query || 'default'}"`);
  } catch (err) {
    showToast(err.message);
  }
}

async function registerServiceWorker() {
  const swLabel = $('#sw-state');
  const cacheLabel = $('#cache-state');

  if (!('serviceWorker' in navigator)) {
    swLabel.textContent = 'Unsupported';
    return;
  }

  try {
    const reg = await navigator.serviceWorker.register('./sw.js', { scope: './' });
    await reg.update().catch(() => {});
    if (reg.waiting) {
      reg.waiting.postMessage({ type: 'SKIP_WAITING' });
    }
    swLabel.textContent = reg.active ? 'Active' : 'Registered';
    if ('caches' in window) {
      const keys = await caches.keys();
      cacheLabel.textContent = keys.length > 0 ? `${keys[0]} ready` : 'Warming';
    }
  } catch (err) {
    swLabel.textContent = 'Error';
    cacheLabel.textContent = err.message;
  }
}

