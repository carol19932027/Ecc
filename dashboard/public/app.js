function createGlassPillLens({
  container,
  thumb,
  itemSelector,
  activeClass = 'is-active',
  hoverClass = 'is-lens-hover',
  scrubClass = 'is-scrubbing',
  pressedClass = 'is-pressed',
  lensClass = 'is-lens',
  popVar = '--tab-pop',
  restHeight = 54,
  restTop = 0,
  liftExtraW = 16,
  liftExtraH = 16,
  maxStretch = 0.16,
  onCommit,
}) {
  if (!container || !thumb) return null;

  const getItems = () => [...container.querySelectorAll(itemSelector)];
  const isReducedMotion = () =>
    state.reducedMotion || window.matchMedia?.('(prefers-reduced-motion: reduce)')?.matches;

  const phys = {
    initialized: false,
    x: 0,
    vx: 0,
    w: 0,
    vw: 0,
    lift: 0,
    vlift: 0,
    targetX: 0,
    targetW: 0,
    targetLift: 0,
    holdLiftUntil: 0,
    rafId: 0,
    lastTs: 0,
    dragging: false,
    moved: false,
    pointerId: null,
    startX: 0,
    downItem: null,
    suppressClickUntil: 0,
  };

  function measure() {
    const items = getItems();
    const metrics = items.map(el => ({
      el,
      left: el.offsetLeft,
      top: el.offsetTop,
      w: el.offsetWidth,
      h: el.offsetHeight || restHeight,
      cx: el.offsetLeft + el.offsetWidth / 2,
    })).filter(m => m.w > 0);
    metrics.sort((a, b) => a.cx - b.cx);
    return metrics;
  }

  function nearestByX(metrics, cx) {
    if (!metrics.length) return null;
    let best = metrics[0];
    let bestDist = Math.abs(metrics[0].cx - cx);
    for (let i = 1; i < metrics.length; i += 1) {
      const d = Math.abs(metrics[i].cx - cx);
      if (d < bestDist) {
        best = metrics[i];
        bestDist = d;
      }
    }
    return best;
  }

  function itemAtClientX(metrics, clientX) {
    const rect = container.getBoundingClientRect();
    const relX = clientX - rect.left;
    const hit = metrics.find(m => relX >= m.left && relX <= m.left + m.w);
    return hit || nearestByX(metrics, relX);
  }

  function rubberBandX(metrics, relX) {
    if (!metrics.length) return relX;
    const minCX = metrics[0].cx;
    const maxCX = metrics[metrics.length - 1].cx;
    if (relX < minCX) return minCX - Math.min(18, (minCX - relX) * 0.28);
    if (relX > maxCX) return maxCX + Math.min(18, (relX - maxCX) * 0.28);
    return relX;
  }

  function applyVisuals(metrics) {
    if (!metrics.length) return;
    const lift = Math.max(0, Math.min(1.15, phys.lift));
    const clampedLift = Math.max(0, Math.min(1, lift));
    const activeW = Math.max(24, phys.w + lift * liftExtraW);
    const activeH = Math.max(20, restHeight + lift * liftExtraH);
    const left = phys.x - activeW / 2;
    const topOffset = restTop - (activeH - restHeight) / 2;

    const speed = Math.abs(phys.vx);
    const stretchX = phys.dragging || clampedLift > 0.05
      ? 1 + Math.min(maxStretch, speed * 0.00018)
      : 1;
    const stretchY = 1 / Math.sqrt(stretchX);

    thumb.style.width = `${activeW.toFixed(2)}px`;
    thumb.style.height = `${activeH.toFixed(2)}px`;
    thumb.style.transform = `translate3d(${left.toFixed(2)}px, ${topOffset.toFixed(2)}px, 0) scale(${stretchX.toFixed(4)}, ${stretchY.toFixed(4)})`;

    const glintShift = Math.max(-24, Math.min(24, phys.vx * 0.025));
    thumb.style.setProperty('--lens-mx', `${(50 + glintShift).toFixed(1)}%`);

    const showLens = phys.dragging || clampedLift > 0.08;
    thumb.classList.toggle(lensClass, showLens);
    container.classList.toggle(scrubClass, phys.dragging);
    container.classList.toggle(pressedClass, phys.dragging);

    const nearest = nearestByX(metrics, phys.x);
    for (const m of metrics) {
      const dist = Math.abs(m.cx - phys.x);
      const rawProx = Math.max(0, 1 - dist / Math.max(24, m.w * 0.85));
      const smoothProx = rawProx * rawProx * (3 - 2 * rawProx);
      const pop = phys.dragging || clampedLift > 0.04 ? smoothProx * clampedLift : 0;
      m.el.style.setProperty(popVar, pop.toFixed(3));
      m.el.classList.toggle(hoverClass, showLens && nearest && m.el === nearest.el);
    }
  }

  function step(now) {
    const metrics = measure();
    if (!metrics.length) {
      phys.rafId = 0;
      return;
    }

    const dt = phys.lastTs ? Math.min(0.032, Math.max(0.004, (now - phys.lastTs) / 1000)) : 1 / 60;
    phys.lastTs = now;

    if (!phys.dragging && phys.holdLiftUntil && now >= phys.holdLiftUntil) {
      phys.holdLiftUntil = 0;
      phys.targetLift = 0;
    }

    if (isReducedMotion()) {
      phys.x = phys.targetX;
      phys.w = phys.targetW;
      phys.lift = phys.dragging ? 1 : 0;
      phys.vx = 0;
      phys.vw = 0;
      phys.vlift = 0;
      applyVisuals(metrics);
      phys.rafId = 0;
      return;
    }

    const stiffnessX = phys.dragging ? 580 : 320;
    const dampingX = phys.dragging ? 44 : 30;
    const ax = (phys.targetX - phys.x) * stiffnessX - phys.vx * dampingX;
    phys.vx += ax * dt;
    phys.x += phys.vx * dt;

    const stiffnessW = 360;
    const dampingW = 32;
    const aw = (phys.targetW - phys.w) * stiffnessW - phys.vw * dampingW;
    phys.vw += aw * dt;
    phys.w += phys.vw * dt;

    const stiffnessL = phys.targetLift > phys.lift ? 420 : 280;
    const dampingL = phys.targetLift > phys.lift ? 30 : 26;
    const al = (phys.targetLift - phys.lift) * stiffnessL - phys.vlift * dampingL;
    phys.vlift += al * dt;
    phys.lift += phys.vlift * dt;

    applyVisuals(metrics);

    const settled =
      !phys.dragging &&
      !phys.holdLiftUntil &&
      Math.abs(phys.targetX - phys.x) < 0.15 &&
      Math.abs(phys.vx) < 0.4 &&
      Math.abs(phys.targetW - phys.w) < 0.15 &&
      Math.abs(phys.targetLift - phys.lift) < 0.008 &&
      Math.abs(phys.vlift) < 0.04;

    if (settled) {
      phys.x = phys.targetX;
      phys.w = phys.targetW;
      phys.lift = phys.targetLift;
      phys.vx = 0;
      phys.vw = 0;
      phys.vlift = 0;
      applyVisuals(metrics);
      phys.rafId = 0;
      phys.lastTs = 0;
      return;
    }

    phys.rafId = requestAnimationFrame(step);
  }

  function ensureRunning() {
    if (!phys.rafId) {
      phys.lastTs = 0;
      phys.rafId = requestAnimationFrame(step);
    }
  }

  function syncToActive({ animate = false } = {}) {
    const metrics = measure();
    if (!metrics.length) return;
    const active = metrics.find(m => m.el.classList.contains(activeClass)) || metrics[0];

    if (!phys.initialized || !animate || isReducedMotion()) {
      phys.initialized = true;
      phys.x = active.cx;
      phys.w = active.w;
      phys.lift = 0;
      phys.vx = 0;
      phys.vw = 0;
      phys.vlift = 0;
      phys.targetX = active.cx;
      phys.targetW = active.w;
      phys.targetLift = 0;
      phys.holdLiftUntil = 0;
      applyVisuals(metrics);
      return;
    }

    const distance = Math.abs(active.cx - phys.x);
    phys.targetX = active.cx;
    phys.targetW = active.w;
    if (!phys.dragging && distance > 10) {
      phys.targetLift = 1;
      phys.holdLiftUntil = performance.now() + 140;
    }
    ensureRunning();
  }

  container.addEventListener('pointerdown', e => {
    if (e.button !== undefined && e.button !== 0) return;
    const metrics = measure();
    if (!metrics.length) return;

    const rect = container.getBoundingClientRect();
    const relX = e.clientX - rect.left;
    const hit = itemAtClientX(metrics, e.clientX);

    phys.dragging = true;
    phys.moved = false;
    phys.pointerId = e.pointerId;
    phys.startX = e.clientX;
    phys.downItem = hit?.el || null;
    phys.holdLiftUntil = 0;
    phys.targetLift = 1;
    if (hit) {
      phys.targetX = hit.cx;
      phys.targetW = hit.w;
    } else {
      phys.targetX = rubberBandX(metrics, relX);
    }

    container.setPointerCapture?.(e.pointerId);
    ensureRunning();
  });

  const handleMove = e => {
    if (!phys.dragging) return;
    if (phys.pointerId !== null && e.pointerId !== undefined && e.pointerId !== phys.pointerId) return;
    const metrics = measure();
    if (!metrics.length) return;

    if (!phys.moved && Math.abs(e.clientX - phys.startX) > 4) {
      phys.moved = true;
    }
    if (!phys.moved) return;

    const rect = container.getBoundingClientRect();
    const relX = e.clientX - rect.left;
    const clampedX = rubberBandX(metrics, relX);
    const nearest = nearestByX(metrics, clampedX);

    phys.targetX = clampedX;
    if (nearest) phys.targetW = nearest.w;
    phys.targetLift = 1;
    ensureRunning();
  };

  const finishPointer = (e, cancelled = false) => {
    if (!phys.dragging) return;
    if (phys.pointerId !== null && e.pointerId !== undefined && e.pointerId !== phys.pointerId) return;

    const metrics = measure();
    const wasMoved = phys.moved;
    const downItem = phys.downItem;

    phys.dragging = false;
    phys.moved = false;
    phys.pointerId = null;
    phys.downItem = null;
    container.releasePointerCapture?.(e.pointerId);

    if (!metrics.length) return;

    let targetMetric = metrics.find(m => m.el.classList.contains(activeClass)) || metrics[0];
    if (!cancelled) {
      if (wasMoved) {
        targetMetric = nearestByX(metrics, phys.x) || itemAtClientX(metrics, e.clientX) || targetMetric;
      } else {
        targetMetric = itemAtClientX(metrics, e.clientX) || metrics.find(m => m.el === downItem) || targetMetric;
      }
      phys.suppressClickUntil = performance.now() + 180;
      if (targetMetric?.el && onCommit) {
        onCommit(targetMetric.el, { viaPointer: true, wasMoved });
      }
    }

    phys.targetX = targetMetric.cx;
    phys.targetW = targetMetric.w;
    if (!wasMoved && !cancelled && Math.abs(targetMetric.cx - phys.x) > 10 && !isReducedMotion()) {
      phys.targetLift = 1;
      phys.holdLiftUntil = performance.now() + 140;
    } else {
      phys.holdLiftUntil = 0;
      phys.targetLift = 0;
    }
    ensureRunning();
  };

  container.addEventListener('pointermove', handleMove);
  container.addEventListener('pointerup', e => finishPointer(e, false));
  container.addEventListener('pointercancel', e => finishPointer(e, true));
  window.addEventListener('pointerup', e => finishPointer(e, false));
  window.addEventListener('pointercancel', e => finishPointer(e, true));

  container.addEventListener('click', e => {
    const item = e.target.closest?.(itemSelector);
    if (!item) return;
    if (e.detail > 0 && performance.now() < phys.suppressClickUntil) {
      e.preventDefault();
      return;
    }
    if (onCommit) onCommit(item, { viaKeyboard: e.detail === 0 });
  });

  container.addEventListener('keydown', e => {
    if (!['ArrowLeft', 'ArrowRight', 'Home', 'End'].includes(e.key)) return;
    const metrics = measure();
    if (!metrics.length) return;
    const currIdx = Math.max(0, metrics.findIndex(m => m.el.classList.contains(activeClass)));
    let nextIdx = currIdx;
    if (e.key === 'ArrowLeft') nextIdx = (currIdx - 1 + metrics.length) % metrics.length;
    if (e.key === 'ArrowRight') nextIdx = (currIdx + 1) % metrics.length;
    if (e.key === 'Home') nextIdx = 0;
    if (e.key === 'End') nextIdx = metrics.length - 1;
    const target = metrics[nextIdx]?.el;
    if (target && onCommit) {
      e.preventDefault();
      target.focus();
      onCommit(target, { viaKeyboard: true });
    }
  });

  syncToActive({ animate: false });
  return { syncToActive };
}

