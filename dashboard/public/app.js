function initNativeSwitchPhysics() {
  syncAllSwitchStates();
  $$('.ios-switch-wrap').forEach(wrap => {
    const input = wrap.querySelector('.ios-switch');
    if (!input) return;
    let startX = 0;
    let dragged = false;

    input.addEventListener('change', () => {
      wrap.classList.toggle('is-checked', input.checked);
    });

    wrap.addEventListener('pointerdown', e => {
      startX = e.clientX;
      dragged = false;
      wrap.classList.add('is-pressed');
    });

    wrap.addEventListener('pointermove', e => {
      if (!wrap.classList.contains('is-pressed')) return;
      const dx = e.clientX - startX;
      if (Math.abs(dx) > 10) {
        dragged = true;
        const targetState = dx > 0;
        if (input.checked !== targetState) {
          input.checked = targetState;
          input.dispatchEvent(new Event('change', { bubbles: true }));
        }
      }
    });

    const release = () => {
      wrap.classList.remove('is-pressed');
      if (dragged) {
        setTimeout(() => { dragged = false; }, 40);
      }
    };

    wrap.addEventListener('pointerup', release);
    wrap.addEventListener('pointercancel', release);
    wrap.addEventListener('pointerleave', release);
  });
}

