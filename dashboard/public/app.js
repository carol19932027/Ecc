const $ = sel => document.querySelector(sel);
const $$ = sel => [...document.querySelectorAll(sel)];

function showToast(msg) {
  const el = $('#toast');
  el.textContent = msg;
  el.hidden = false;
  clearTimeout(showToast._timer);
  showToast._timer = setTimeout(() => { el.hidden = true; }, 2800);
}

function logActivity(text, tone = 'ok') {
  const time = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
  state.activities.unshift({ text, tone, time });
  state.activities = state.activities.slice(0, 8);
  renderActivities();
}

function renderActivities() {
  const list = $('#activity-list');
  const count = $('#activity-count');
  count.textContent = String(state.activities.length);
  list.innerHTML = state.activities.map(item => `
    <li class="activity-item">
      <span class="activity-left">
        <span class="activity-dot" style="background: var(--${item.tone === 'warn' ? 'warn' : 'ok'})"></span>
        <span>${escapeHtml(item.text)}</span>
      </span>
      <span class="activity-time tabular">${escapeHtml(item.time)}</span>
    </li>
  `).join('');
}

function escapeHtml(str) {
  return String(str || '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function applyPreferences() {
  const root = document.documentElement;
  root.dataset.theme = state.theme;
  root.dataset.tint = state.tint;
  root.dataset.reducedMotion = state.reducedMotion ? 'true' : 'false';
  root.style.setProperty('--glass-blur', `${state.blur}px`);
  root.lang = state.lang;
  root.dir = state.lang === 'fa' ? 'rtl' : 'ltr';

  $('#lang-badge').textContent = state.lang === 'fa' ? 'EN' : 'FA';
  $('#meta-theme-color').setAttribute('content', state.theme === 'dark' ? '#070c1b' : '#e7f0fb');
  $('#blur-range').value = String(state.blur);
  $('#blur-val').textContent = `${state.blur}px`;
  $('#toggle-motion').checked = state.reducedMotion;

  $$('[data-set-tint]').forEach(btn => {
    btn.classList.toggle('is-active', btn.dataset.setTint === state.tint);
  });

  const dict = I18N[state.lang] || I18N.en;
  $$('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });
  $$('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });

  updateConnectionBanner();
  requestAnimationFrame(positionDockIndicator);
}

function updateConnectionBanner() {
  const online = navigator.onLine;
  const dict = I18N[state.lang] || I18N.en;
  $('#connection-dot').classList.toggle('is-offline', !online);
  $('#connection-label').textContent = online ? dict.live : dict.offline;
}

function switchView(viewId) {
  state.activeView = viewId;
  $$('.view').forEach(sec => {
    sec.hidden = sec.id !== `view-${viewId}`;
    sec.classList.toggle('is-active', sec.id === `view-${viewId}`);
  });
  $$('.dock-tab').forEach(tab => {
    tab.classList.toggle('is-active', tab.dataset.view === viewId);
  });
  positionDockIndicator();
  if (viewId === 'pulse') {
    requestAnimationFrame(drawTelemetryChart);
  }
}

function positionDockIndicator() {
  const track = $('#dock-track');
  const indicator = $('#dock-indicator');
  const activeTab = track?.querySelector('.dock-tab.is-active');
  if (!track || !indicator || !activeTab) return;

  indicator.style.width = `${activeTab.offsetWidth}px`;
  indicator.style.height = `${activeTab.offsetHeight}px`;
  indicator.style.transform = `translate3d(${activeTab.offsetLeft}px, ${activeTab.offsetTop}px, 0)`;
}

function updateReadinessGauge() {
  const checkedCount = $$('#loops-list input[type="checkbox"]:checked').length;
  const score = Math.min(99, 82 + checkedCount * 4);
  const circumference = 2 * Math.PI * 48;
  const offset = circumference * (1 - score / 100);
  $('#readiness-score').textContent = `${score}%`;
  $('#gauge-arc').style.strokeDasharray = circumference.toFixed(1);
  $('#gauge-arc').style.strokeDashoffset = offset.toFixed(1);
}

function drawTelemetryChart() {
  const points = state.telemetrySeries[state.chartWindow] || [];
  const lineEl = $('#chart-line');
  const areaEl = $('#chart-area');
  if (!lineEl || !areaEl || points.length < 2) return;

  const w = 360;
  const h = 150;
  const padY = 14;

  const coords = points.map((pt, i) => ({
    x: (i / (points.length - 1)) * w,
    y: h - padY - ((pt.value / 100) * (h - padY * 2)),
    val: pt.value,
  }));

  let lineD = `M ${coords[0].x.toFixed(1)},${coords[0].y.toFixed(1)}`;
  for (let i = 0; i < coords.length - 1; i += 1) {
    const p0 = coords[i];
    const p1 = coords[i + 1];
    const cx = ((p0.x + p1.x) / 2).toFixed(1);
    lineD += ` C ${cx},${p0.y.toFixed(1)} ${cx},${p1.y.toFixed(1)} ${p1.x.toFixed(1)},${p1.y.toFixed(1)}`;
  }

  const areaD = `${lineD} L ${w},${h} L 0,${h} Z`;
  lineEl.setAttribute('d', lineD);
  areaEl.setAttribute('d', areaD);
  drawTelemetryChart._coords = coords;
}

function attachChartScrubbing() {
  const wrap = $('#chart-wrap');
  const svg = $('#telemetry-svg');
  const crosshair = $('#chart-crosshair');
  const dot = $('#chart-focus-dot');
  const tip = $('#chart-tooltip');

  function updateAtClientX(clientX) {
    const coords = drawTelemetryChart._coords;
    if (!coords || coords.length === 0) return;
    const rect = svg.getBoundingClientRect();
    const ratio = Math.max(0, Math.min(1, (clientX - rect.left) / rect.width));
    const idx = Math.round(ratio * (coords.length - 1));
    const pt = coords[idx];
    crosshair.setAttribute('x1', pt.x);
    crosshair.setAttribute('x2', pt.x);
    crosshair.setAttribute('opacity', '1');
    dot.setAttribute('cx', pt.x);
    dot.setAttribute('cy', pt.y);
    dot.setAttribute('opacity', '1');
    tip.textContent = `${pt.val}%`;
    tip.hidden = false;
  }

  function clearScrub() {
    crosshair.setAttribute('opacity', '0');
    dot.setAttribute('opacity', '0');
    tip.hidden = true;
  }

  wrap.addEventListener('pointermove', e => updateAtClientX(e.clientX));
  wrap.addEventListener('pointerdown', e => updateAtClientX(e.clientX));
  wrap.addEventListener('pointerleave', clearScrub);
}

function attachPointerGlint() {
  let raf = 0;
  document.addEventListener('pointermove', e => {
    const card = e.target.closest?.('.interactive-glass');
    if (!card || raf) return;
    raf = requestAnimationFrame(() => {
      raf = 0;
      const rect = card.getBoundingClientRect();
      card.style.setProperty('--mx', `${e.clientX - rect.left}px`);
      card.style.setProperty('--my', `${e.clientY - rect.top}px`);
    });
  }, { passive: true });
}

function renderTargets(targets = []) {
  const container = $('#targets-list');
  container.innerHTML = targets.map(t => `
    <div class="target-item">
      <div>
        <strong>${escapeHtml(t.target)} <span style="opacity:.6;font-weight:500">(${escapeHtml(t.targetRoot)})</span></strong>
        <small>${t.installed ? `${t.fileCount} files synced` : 'Not installed in workspace'}</small>
      </div>
      <span class="kind-badge glass-pill" style="color: var(--${t.installed ? 'ok' : 'text-muted'})">
        ${t.installed ? 'Synced' : 'Standby'}
      </span>
    </div>
  `).join('');
}

function renderCatalog() {
  const q = state.searchQuery.trim().toLowerCase();
  const filtered = state.catalog.filter(item => {
    if (state.filterKind !== 'all' && item.kind !== state.filterKind) return false;
    if (!q) return true;
    return item.id.toLowerCase().includes(q)
      || item.title.toLowerCase().includes(q)
      || item.description.toLowerCase().includes(q);
  });

  $('#catalog-match-count').textContent = String(filtered.length);
  const grid = $('#catalog-grid');
  grid.innerHTML = filtered.map(item => `
    <button type="button" class="comp-card glass-card interactive-glass" data-open-kind="${escapeHtml(item.kind)}" data-open-id="${escapeHtml(item.id)}">
      <div class="comp-top">
        <span class="kind-badge glass-pill">${escapeHtml(item.kind)}</span>
        ${item.canonical?.length ? `<span class="kpi-badge">→ ${escapeHtml(item.canonical[0])}</span>` : ''}
      </div>
      <h3 class="comp-title">${escapeHtml(item.id)}</h3>
      <p class="comp-desc">${escapeHtml(item.description)}</p>
    </button>
  `).join('');
}

async function openComponentSheet(kind, id) {
  try {
    const res = await fetch(`/api/component/${encodeURIComponent(kind)}/${encodeURIComponent(id)}`);
    const data = await res.json();
    if (!res.ok || !data.ok) throw new Error(data.error || 'Failed to load component');
    state.activeComponent = data;
    $('#sheet-kind').textContent = `${data.kind} · ${data.relativePath}`;
    $('#sheet-title').textContent = data.title || data.id;
    $('#sheet-desc').textContent = data.description || '';
    $('#sheet-body').textContent = data.content || '';
    $('#sheet-backdrop').hidden = false;
  } catch (err) {
    showToast(err.message);
  }
}

function closeComponentSheet() {
  $('#sheet-backdrop').hidden = true;
}

async function runDryRunPreview(skills, target = 'arena') {
  const res = await fetch('/api/install-preview', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ target, skills }),
  });
  const data = await res.json();
  if (!res.ok || !data.ok) throw new Error(data.error || 'Preview failed');
  showToast(`${data.target}: ${data.operationCount} file ops ready (${data.selection.skills.length} skills, ${data.selection.agents.length} agents)`);
  logActivity(`Dry-run ${target}: ${data.operationCount} operations planned`);
}

async function runAction(action) {
  try {
    const res = await fetch('/api/action', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ action }),
    });
    const data = await res.json();
    if (!res.ok || !data.ok) throw new Error(data.error || 'Action failed');

    if (action === 'audit') {
      const msg = data.issues.length === 0
        ? `Audit passed (${data.targetsChecked.join(', ')})`
        : `Audit found ${data.issues.length} issue(s)`;
      showToast(msg);
      logActivity(msg, data.issues.length === 0 ? 'ok' : 'warn');
    } else if (action === 'sync-arena') {
      showToast(`Arena synced: ${data.summary.total} files verified`);
      logActivity(`Arena synced (${data.summary.created} created, ${data.summary.unchanged} unchanged)`);
      await fetchStatus();
    } else if (action === 'telemetry-pulse') {
      applyTelemetry(data.telemetry);
      showToast('Telemetry refreshed');
      logActivity('Telemetry waveform sampled');
    }
  } catch (err) {
    showToast(err.message);
    logActivity(err.message, 'warn');
  }
}

function applyTelemetry(t) {
  if (!t) return;
  $('#stat-cpu').textContent = `${t.cpuPct}%`;
  $('#stat-mem').textContent = `${t.memPct}%`;
  $('#stat-uptime').textContent = `${t.uptimeSec}s`;
  state.telemetrySeries = t.series || state.telemetrySeries;
  drawTelemetryChart();
}

async function fetchStatus() {
  try {
    const res = await fetch('/api/status');
    const data = await res.json();
    if (!res.ok || !data.ok) return;

    $('#kpi-skills').textContent = String(data.counts.skills);
    $('#kpi-agents').textContent = String(data.counts.agents);
    $('#kpi-commands').textContent = String(data.counts.commands);
    $('#kpi-shims').textContent = String(data.counts.shims);

    const activeTargets = (data.targets || []).filter(t => t.installed).length;
    $('#stat-targets').textContent = `${activeTargets}/${(data.targets || []).length}`;

    applyTelemetry(data.telemetry);
    renderTargets(data.targets || []);
  } catch {
    updateConnectionBanner();
  }
}

