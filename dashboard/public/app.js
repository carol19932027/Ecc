function recommendLocally(query, items) {
  const raw = String(query || '').trim().toLowerCase();
  if (!raw) {
    return {
      query: '',
      matches: items.slice(0, 6),
      command: 'ecc-install --skills blueprint,tdd-workflow,verification-loop,code-reviewer',
    };
  }
  const tokens = raw.split(/[\s,،؛.+/_-]+/).map(t => t.trim()).filter(Boolean);
  const expanded = new Set(tokens);
  for (const tok of tokens) {
    for (const [fa, aliases] of Object.entries(PERSIAN_INTENT_ALIASES)) {
      if (tok.includes(fa) || fa.includes(tok)) aliases.forEach(a => expanded.add(a));
    }
  }
  const scored = items.map(item => {
    const idL = item.id.toLowerCase();
    const titleL = (item.title || '').toLowerCase();
    const descL = (item.description || '').toLowerCase();
    let score = 0;
    if (idL === raw) score += 100;
    if (idL.includes(raw)) score += 35;
    for (const tok of expanded) {
      if (tok.length < 2) continue;
      if (idL === tok) score += 45;
      else if (idL.includes(tok)) score += 20;
      if (titleL.includes(tok)) score += 12;
      if (descL.includes(tok)) score += 6;
    }
    if (score > 0 && item.kind === 'skill') score += 4;
    return { ...item, score };
  })
    .filter(x => x.score > 0)
    .sort((a, b) => b.score - a.score || a.id.localeCompare(b.id))
    .slice(0, 8);
  const selected = scored.length > 0 ? scored : items.filter(i => ['plan', 'tdd-workflow', 'verification-loop', 'code-reviewer'].includes(i.id));
  const ids = [...new Set(selected.map(s => s.id))];
  return { query, matches: selected, command: `ecc-install --skills ${ids.join(',')}` };
}

async function openComponentSheet(kind, id) {
  try {
    let data = null;
    try {
      const res = await fetch(`/api/component/${encodeURIComponent(kind)}/${encodeURIComponent(id)}`);
      if (res.ok) data = await res.json();
    } catch {
      // Static preview fallback below
    }
    if (!data?.ok) {
      const bundle = await loadPreviewBundle();
      data = bundle?.components?.[`${kind}/${id}`] || null;
    }
    if (!data || !data.ok) throw new Error('Failed to load component');
    state.activeComponent = data;
    $('#component-sheet').style.transform = '';
    $('#sheet-kind').textContent = `${data.kind} · ${data.relativePath}`;
    $('#sheet-title').textContent = data.title || data.id;
    $('#sheet-desc').textContent = data.description || '';
    $('#sheet-body').textContent = data.content || '';
    $('#sheet-actions-row').hidden = false;
    $('#sheet-backdrop').hidden = false;
  } catch (err) {
    showToast(err.message);
  }
}

