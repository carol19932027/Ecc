const $ = sel => document.querySelector(sel);
const $$ = sel => [...document.querySelectorAll(sel)];

function showToast(msg) {
  const el = $('#toast');
  el.textContent = msg;
  el.hidden = false;
  clearTimeout(showToast._timer);
  showToast._timer = setTimeout(() => { el.hidden = true; }, 2800);
}

function logActivity(text, tone = 'ok') {
  const time = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
  state.activities.unshift({ text, tone, time });
  state.activities = state.activities.slice(0, 8);
  renderActivities();
}

function renderActivities() {
  const list = $('#activity-list');
  const count = $('#activity-count');
  count.textContent = String(state.activities.length);
  list.innerHTML = state.activities.map(item => `
    <li class="activity-item">
      <span class="activity-left">
        <span class="activity-dot" style="background: var(--${item.tone === 'warn' ? 'warn' : 'ok'})"></span>
        <span>${escapeHtml(item.text)}</span>
      </span>
      <span class="activity-time tabular">${escapeHtml(item.time)}</span>
    </li>
  `).join('');
}

function escapeHtml(str) {
  return String(str || '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function getPaletteEntry(tintId) {
  return IOS27_PALETTE.find(p => p.id === tintId) || IOS27_PALETTE[0];
}

function renderIos27Swatches() {
  const grid = $('#ios27-swatch-grid');
  if (!grid) return;

  const palette = IOS27_PALETTE.map(entry => {
    const darkTok = state.ios27Tokens?.systemColors?.Dark?.[entry.tokenKey]?.hex;
    const lightTok = state.ios27Tokens?.systemColors?.Light?.[entry.tokenKey]?.hex;
    return {
      ...entry,
      dark: darkTok || entry.dark,
      light: lightTok || entry.light,
    };
  });

  grid.innerHTML = palette.map(p => {
    const hex = state.theme === 'dark' ? p.dark : p.light;
    const active = state.tint === p.id ? 'is-active' : '';
    return `
      <button type="button" class="swatch-btn ${active}" data-set-tint="${escapeHtml(p.id)}">
        <span class="swatch-circle" style="background:${escapeHtml(hex)}"></span>
        <span>${escapeHtml(p.label)}</span>
      </button>
    `;
  }).join('');

  grid.querySelectorAll('[data-set-tint]').forEach(btn => {
    btn.addEventListener('click', () => {
      state.tint = btn.dataset.setTint;
      localStorage.setItem('ecc_tint', state.tint);
      applyPreferences();
      showToast(`iOS 27 System ${getPaletteEntry(state.tint).label} applied`);
    });
  });
}

function syncSliderGeometry() {
  const slider = $('#blur-range');
  const fill = $('#blur-slider-fill');
  const thumb = $('#blur-slider-thumb');
  if (!slider || !fill || !thumb) return;

  const min = Number(slider.min || 6);
  const max = Number(slider.max || 45);
  const val = Number(slider.value || state.blur);
  const pct = Math.max(0, Math.min(100, ((val - min) / (max - min)) * 100));

  fill.style.width = `${pct}%`;
  const visualLeftPct = document.documentElement.dir === 'rtl' ? (100 - pct) : pct;
  thumb.style.left = `${visualLeftPct}%`;
}

function applyPreferences() {
  const root = document.documentElement;
  root.dataset.theme = state.theme;
  root.dataset.tint = state.tint;
  root.dataset.reducedMotion = state.reducedMotion ? 'true' : 'false';
  root.style.setProperty('--glass-blur', `${state.blur}px`);
  root.style.setProperty('--glass-blur-small', `${Math.max(2, Math.round(state.blur * 0.18))}px`);
  root.lang = state.lang;
  root.dir = state.lang === 'fa' ? 'rtl' : 'ltr';

  $('#lang-badge').textContent = state.lang === 'fa' ? 'EN' : 'FA';
  $('#meta-theme-color').setAttribute('content', state.theme === 'dark' ? '#000000' : '#F2F2F7');
  $('#blur-range').value = String(state.blur);
  $('#blur-val').textContent = `${state.blur}px`;
  $('#toggle-motion').checked = state.reducedMotion;
  syncAllSwitchStates();

  const activeEntry = getPaletteEntry(state.tint);
  const activeHex = state.theme === 'dark' ? activeEntry.dark : activeEntry.light;
  const hexBadge = $('#tokens-accent-hex');
  if (hexBadge) hexBadge.textContent = activeHex;
  const readoutName = $('.swatch-readout-name');
  const readoutHex = $('#swatch-readout-hex');
  if (readoutName) readoutName.textContent = `System ${activeEntry.label}`;
  if (readoutHex) readoutHex.textContent = `Dark ${activeEntry.dark} · Light ${activeEntry.light}`;

  $$('[data-set-tint]').forEach(btn => {
    btn.classList.toggle('is-active', btn.dataset.setTint === state.tint);
  });

  const dict = I18N[state.lang] || I18N.en;
  $$('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });
  $$('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });

  renderIos27Swatches();
  syncSliderGeometry();
  updateConnectionBanner();
  updateInlineNavbarTitle();
  requestAnimationFrame(() => {
    positionDockIndicator();
    positionSegThumb();
  });
}

function updateConnectionBanner() {
  const online = navigator.onLine;
  const dict = I18N[state.lang] || I18N.en;
  $('#connection-dot').classList.toggle('is-offline', !online);
  if (!online) {
    $('#connection-label').textContent = dict.offline;
  } else {
    $('#connection-label').textContent = state.staticPreview ? dict.preview : dict.live;
  }
}

function updateInlineNavbarTitle() {
  const nav = $('#ios-navbar');
  const dockShell = $('.dock-shell');
  const inline = $('#navbar-inline-title');
  const activeSec = $(`#view-${state.activeView}`);
  const titleEl = activeSec?.querySelector('.ios-large-title');
  if (inline && titleEl) inline.textContent = titleEl.textContent;

  const titleRect = titleEl?.getBoundingClientRect();
  const pastLargeTitle = titleRect ? titleRect.bottom <= 68 : window.scrollY > 42;
  const scrolled = window.scrollY > 12 || pastLargeTitle;
  if (nav) nav.classList.toggle('is-scrolled', pastLargeTitle || window.scrollY > 46);
  if (dockShell) dockShell.classList.toggle('is-scrolled', scrolled);
}

